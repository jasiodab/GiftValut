export function suggestCategory<T extends CategoryLike>(
  input: { name?: string | null; description?: string | null; storeName?: string | null; tags?: string[] },
  categories: T[]
): T | null {
  const name = (input.name ?? "").toLocaleLowerCase("pl");
  const description = (input.description ?? "").toLocaleLowerCase("pl");
  const store = (input.storeName ?? "").toLocaleLowerCase("pl");
  const tags = (input.tags ?? []).join(" ").toLocaleLowerCase("pl");

  let bestSlug: string | null = null;
  let bestScore = 0;

  for (const rule of categoryRules) {
    let score = 0;
    for (const keyword of rule.keywords) {
      const normalizedKeyword = keyword.toLocaleLowerCase("pl");
      if (name.includes(normalizedKeyword)) score += 4;
      if (tags.includes(normalizedKeyword)) score += 2;
      if (description.includes(normalizedKeyword)) score += 1;
      if (store.includes(normalizedKeyword)) score += 1;
    }
    if (score > bestScore) {
      bestScore = score;
      bestSlug = rule.slug;
    }
  }

  const matched = bestSlug ? categories.find((category) => category.slug === bestSlug) : null;
  if (matched) return matched;
  return categories.find((category) => category.slug === "other") ?? categories[0] ?? null;
}
